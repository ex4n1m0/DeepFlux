    /** True when the host (or its parent domain) is on the blocklist. */
    fun isBlocked(host: String): Boolean {
        if (host.isBlank()) return false
        val h = host.lowercase().trimEnd('.')
        var parts = h
        while (true) {
            if (parts in blocked) return true
            val dot = parts.indexOf('.')
            if (dot < 0 || dot == parts.length - 1) return false
            parts = parts.substring(dot + 1)
        }
    }
