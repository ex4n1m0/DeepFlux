"""Emit the obfuscated shared key pairs for the ANDROID build.

Android mirror of the desktop ritual (packaging/gen_embedded_keys.py +
gen_embedded_keys_from_env.py): the shared keys never exist as plaintext
constants in the repo or the APK. The AGENT key (since 1.4.12, owner
2026-11-17) is the shared Venice AI key — the uncensored DeepSeek agent
provider. Sources, in order:

* ``--from-embedded`` (default when ``_embedded_keys.py`` exists): read the
  repo-root untracked module (the build machine's key store).
* ``--from-env``: read ``DF_EMBED_VENICE_API_KEY`` or
  ``EMBED_SHARED_VENICE_API_KEY`` (the CI secret name, same as the Linux
  build) — used by .github/workflows/android-build.yml.

Output: ``android/app/embedded_key.properties`` (gitignored) with
``venice_salt_hex`` / ``venice_blob_hex`` (the agent pair) plus the
metadata-provider pairs, where ``blob = key XOR sha256(salt+counter)``
reused VERBATIM from the desktop encoder (imported by path — single source
of truth for the scheme). ``android/app/build.gradle.kts`` turns the pairs
into BuildConfig fields; ``EmbeddedKey.kt`` decodes at runtime. Never
prints values. Refuses to overwrite an existing file unless
``DF_OVERWRITE_EMBEDDED_KEYS=1`` (same guard as the desktop script).
"""
from __future__ import annotations

import base64
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_PATH = os.path.join(ROOT, "android", "app", "embedded_key.properties")


def _load_desktop_encoder():
    path = os.path.join(HERE, "gen_embedded_keys.py")
    spec = importlib.util.spec_from_file_location("desktop_gen_embedded_keys", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _shared_key_from_embedded_file(desktop_gen, attr: str) -> str:
    path = os.path.join(ROOT, "_embedded_keys.py")
    if not os.path.isfile(path):
        return ""
    spec = importlib.util.spec_from_file_location("_embedded_keys_android_src", path)
    src = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(src)
    return desktop_gen.decode_shared_value(getattr(src, attr, ""))


def main() -> int:
    args = set(sys.argv[1:])
    desktop_gen = _load_desktop_encoder()

    if "--from-env" in args:
        value = os.environ.get("DF_EMBED_VENICE_API_KEY") or os.environ.get("EMBED_SHARED_VENICE_API_KEY") or ""
        tmdb = os.environ.get("DF_EMBED_TMDB_API_KEY") or ""
        extra = {}
        source = "env"
    else:
        value = _shared_key_from_embedded_file(desktop_gen, "SHARED_VENICE_API_KEY")
        tmdb = _shared_key_from_embedded_file(desktop_gen, "SHARED_TMDB_API_KEY")
        extra = {
            name: _shared_key_from_embedded_file(desktop_gen, attr)
            for name, attr in (
                ("tpdb", "SHARED_TPDB_API_KEY"),
                ("stashdb", "SHARED_STASHDB_API_KEY"),
            )
        }
        source = "_embedded_keys.py"

    if not value:
        print(f"no key available from {source} — build will be KEYLESS (dev build)")
        if os.path.exists(OUT_PATH):
            print("leaving existing embedded_key.properties untouched")
        return 0

    if os.path.exists(OUT_PATH) and os.environ.get("DF_OVERWRITE_EMBEDDED_KEYS") != "1":
        print(
            f"{OUT_PATH} already exists — set DF_OVERWRITE_EMBEDDED_KEYS=1 to re-embed "
            "(same guard as the desktop script)"
        )
        return 1

    salt_b64, blob_b64 = desktop_gen.encode_shared_value(value)
    salt_hex = base64.b64decode(salt_b64).hex()
    blob_hex = base64.b64decode(blob_b64).hex()
    lines = [
        "# GENERATED by packaging/gen_android_key.py - gitignored, never commit.\n",
        f"venice_salt_hex={salt_hex}\n",
        f"venice_blob_hex={blob_hex}\n",
    ]
    # Shared TMDb pair (1.3.5, movie/series covers); absent key → empty pair
    # → the app falls back to the keyless TVmaze provider.
    if tmdb:
        t_salt_b64, t_blob_b64 = desktop_gen.encode_shared_value(tmdb)
        lines.append(f"tmdb_salt_hex={base64.b64decode(t_salt_b64).hex()}\n")
        lines.append(f"tmdb_blob_hex={base64.b64decode(t_blob_b64).hex()}\n")
    # Adult-metadata providers (1.4.0, desktop iptv/metadata.py chain).
    for name, key in extra.items():
        if key:
            e_salt_b64, e_blob_b64 = desktop_gen.encode_shared_value(key)
            lines.append(f"{name}_salt_hex={base64.b64decode(e_salt_b64).hex()}\n")
            lines.append(f"{name}_blob_hex={base64.b64decode(e_blob_b64).hex()}\n")

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    tmp = OUT_PATH + ".tmp"
    with open(tmp, "w", encoding="ascii", newline="\n") as f:
        f.writelines(lines)
    os.replace(tmp, OUT_PATH)
    # Never print the values or their encodings.
    embedded = ["venice"] + [n for n in ("tmdb",) + tuple(extra) if (tmdb if n == "tmdb" else extra.get(n))]
    print(f"wrote {OUT_PATH} (keys embedded: {', '.join(embedded)}; source: {source})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
